# Regenerates apps/mobile/lib/core/tokens.dart from packages/tokens/tokens.json.
# The Dart file is generated output: edit the token source and re-run this, never hand-edit the Dart.
# Requires only Windows PowerShell + .NET (no network, no Flutter, no package installs).
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/make-tokens-dart.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/make-tokens-dart.ps1 -Check   # CI drift gate
param(
    [switch]$Check
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$tokenPath = Join-Path $root "packages/tokens/tokens.json"
$outPath = Join-Path $root "apps/mobile/lib/core/tokens.dart"

$tokens = Get-Content -Raw -Encoding UTF8 $tokenPath | ConvertFrom-Json

function Get-Hex([string]$value) {
    if ($value -notmatch '^#[0-9a-fA-F]{6}$') { throw "not a 6-digit hex colour: '$value'" }
    return "0xFF" + $value.TrimStart("#").ToUpperInvariant()
}

function Get-Num($value) {
    # Dart needs a decimal point or it reads the token as an int and every EdgeInsets breaks.
    # Invariant culture on purpose: a de-DE runner would otherwise emit "1,0" and corrupt the source.
    return [string]::Format([System.Globalization.CultureInfo]::InvariantCulture, "{0:0.0####}", [double]$value)
}

$lines = New-Object System.Collections.Generic.List[string]
function Emit([string]$text) { $lines.Add($text) }

Emit "// Generated by tools/make-tokens-dart.ps1 from packages/tokens/tokens.json."
Emit "// Do not hand-edit: change the token source and re-run the script."
Emit ""
Emit "import 'package:flutter/material.dart';"
Emit ""

# --- colours ---------------------------------------------------------------
Emit "/// Every brand colour. Grouped exactly as the token file groups them."
Emit "abstract final class E7Color {"
$color = $tokens.color
$numericGroups = @("brand", "accent", "ink")
foreach ($group in $numericGroups) {
    foreach ($step in $color.$group.PSObject.Properties.Name) {
        if ($step -eq "note") { continue }
        Emit ("  static const Color {0}{1} = Color({2});" -f $group, $step, (Get-Hex $color.$group.$step))
    }
}
# surface/state keys are already unique so they keep their bare name (E7Color.canvas,
# E7Color.warningBg). select is a role rather than a colour name, so it carries the group
# prefix. Ordered so the generated file is byte-identical on every machine.
$namedGroups = [ordered]@{ surface = ""; state = ""; select = "select" }
foreach ($group in $namedGroups.Keys) {
    $prefix = $namedGroups[$group]
    foreach ($key in $color.$group.PSObject.Properties.Name) {
        if ($key -eq "note") { continue }
        $member = if ($prefix) { $prefix + $key.Substring(0, 1).ToUpper() + $key.Substring(1) } else { $key }
        Emit ("  static const Color {0} = Color({1});" -f $member, (Get-Hex $color.$group.$key))
    }
}
Emit "}"
Emit ""

# --- scalar groups ---------------------------------------------------------
function Emit-Class([string]$name, [string]$doc, $map, [string]$prefix) {
    Emit "/// $doc"
    Emit "abstract final class $name {"
    foreach ($prop in $map.PSObject.Properties) {
        # "note" is documentation, and layout carries strings (locale, currency) that
        # belong to the formatting layer, not to a Dart size constant.
        if ($prop.Value -isnot [ValueType]) { continue }
        $member = if ($prefix) { "$prefix$($prop.Name)" } else { $prop.Name }
        Emit ("  static const double {0} = {1};" -f $member, (Get-Num $prop.Value))
    }
    Emit "}"
    Emit ""
}

Emit-Class "E7Radius" "Corner radii: cards, controls, pills." $tokens.radius ""
Emit-Class "E7Space" "Spacing scale. Use these, never a literal." $tokens.space ""
Emit-Class "E7Control" "Touch target sizes for the customer app." $tokens.control ""
Emit-Class "E7Layout" "Layout thresholds shared with the token file." $tokens.layout ""

# --- elevation (two levels deep) -------------------------------------------
Emit "/// Card shadows. Tinted with ink900 at a low alpha instead of Material's grey."
Emit "abstract final class E7Elevation {"
foreach ($level in $tokens.elevation.PSObject.Properties) {
    if ($level.Name -eq "note") { continue }
    foreach ($axis in $level.Value.PSObject.Properties) {
        $member = "{0}{1}{2}" -f $level.Name, $axis.Name.Substring(0, 1).ToUpper(), $axis.Name.Substring(1)
        Emit ("  static const double {0} = {1};" -f $member, (Get-Num $axis.Value))
    }
}
Emit "  // withValues() is not const-evaluable, so the resolved shadows are getters."
Emit "  static BoxShadow get cardShadow => BoxShadow("
Emit "      color: E7Color.ink900.withValues(alpha: cardAlpha),"
Emit "      offset: const Offset(0, cardOffsetY),"
Emit "      blurRadius: cardBlur);"
Emit "  static BoxShadow get raisedShadow => BoxShadow("
Emit "      color: E7Color.ink900.withValues(alpha: raisedAlpha),"
Emit "      offset: const Offset(0, raisedOffsetY),"
Emit "      blurRadius: raisedBlur);"
Emit "}"
Emit ""

# --- typography ------------------------------------------------------------
$typo = $tokens.typography
Emit "/// Font families and the reading rhythm. Fallback stack is the token file's, order preserved."
Emit "abstract final class E7Font {"
Emit ("  static const String display = '{0}';" -f $typo.fontFamilyDisplay)
Emit ("  static const String text = '{0}';" -f $typo.fontFamilyText)
Emit ("  static const List<String> fallback = <String>[{0}];" -f (($typo.fallback | ForEach-Object { "'$_'" }) -join ", "))
# lineHeight is the body rhythm, so it lands as textLineHeight beside the text family;
# "display" is already taken by the heading family. Everything else keeps its token name.
$typoRename = @{ lineHeight = "textLineHeight" }
foreach ($prop in $typo.PSObject.Properties) {
    if ($prop.Value -isnot [ValueType]) { continue }
    $member = if ($typoRename.ContainsKey($prop.Name)) { $typoRename[$prop.Name] } else { $prop.Name }
    Emit ("  static const double {0} = {1};" -f $member, (Get-Num $prop.Value))
}
Emit "}"
Emit ""

$content = ($lines -join "`n")

if ($Check) {
    if (-not (Test-Path $outPath)) { Write-Error "tokens.dart is missing - run tools/make-tokens-dart.ps1"; exit 1 }
    $current = (Get-Content -Raw -Encoding UTF8 $outPath) -replace "`r`n", "`n"
    if ($current.TrimEnd() -ne $content.TrimEnd()) {
        Write-Output "tokens.dart is out of sync with packages/tokens/tokens.json."
        Write-Output "Run: powershell -NoProfile -ExecutionPolicy Bypass -File tools/make-tokens-dart.ps1"
        exit 1
    }
    Write-Output "tokens.dart matches packages/tokens/tokens.json"
    exit 0
}

# Dart sources are UTF-8 without a BOM, and LF so the file reads the same on every platform.
$encoding = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($outPath, $content, $encoding)

$count = ($lines | Where-Object { $_ -match "static const|static BoxShadow get" }).Count
Write-Output "wrote $outPath ($count values)"
